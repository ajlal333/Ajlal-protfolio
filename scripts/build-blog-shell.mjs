/**
 * Post-build step for the LogicFolds site.
 *
 * Blog posts live in Supabase and are rendered per request by Netlify
 * Functions, so this script no longer writes article pages. What it does write
 * is the shell those functions need:
 *
 *   netlify/functions/blog-shell.mjs
 *     - the hashed <link>/<script> tags Vite emitted for the blog entry
 *     - the nav, footer and booking dialog markup, lifted from blog/post.html
 *       so editing that file updates every blog page
 *     - a snapshot of content/blog-posts.json, used as the offline fallback
 *       when Supabase is unconfigured, paused or down
 *
 * It also writes robots.txt and resolves the __SITE_URL__ placeholder in the
 * hand-written entry HTML. sitemap.xml is served by a function now, because it
 * has to list posts that were published without a deploy.
 */

import { readFile, writeFile, rm, readdir } from 'node:fs/promises';
import { resolve, join } from 'node:path';

const DIST = resolve('dist');
const FALLBACK_SITE_URL = 'https://logicfolds.netlify.app';

const rawSiteUrl =
  process.env.SITE_URL || process.env.URL || process.env.DEPLOY_PRIME_URL || '';

if (!rawSiteUrl) {
  console.warn(
    `[blog-shell] No SITE_URL/URL env var set. Falling back to ${FALLBACK_SITE_URL} ` +
      'for absolute metadata URLs. Netlify sets URL automatically in production.'
  );
}

const SITE_URL = (rawSiteUrl || FALLBACK_SITE_URL).replace(/\/+$/, '');

/** Pull a balanced top-level block such as <nav ...>...</nav> out of built HTML. */
function extractBlock(html, tagName) {
  const start = html.search(new RegExp(`<${tagName}[\\s>]`, 'i'));
  if (start === -1) return '';

  const openTag = new RegExp(`<${tagName}\\b`, 'gi');
  const closeTag = new RegExp(`</${tagName}>`, 'gi');
  let depth = 0;
  let cursor = start;

  while (cursor < html.length) {
    openTag.lastIndex = cursor;
    closeTag.lastIndex = cursor;
    const next = openTag.exec(html);
    const close = closeTag.exec(html);
    if (!close) break;

    if (next && next.index < close.index) {
      depth += 1;
      cursor = next.index + next[0].length;
    } else {
      depth -= 1;
      cursor = close.index + close[0].length;
      if (depth === 0) return html.slice(start, cursor);
    }
  }

  return '';
}

function extractAssetTags(html) {
  const head = html.match(/<head[^>]*>([\s\S]*?)<\/head>/i)?.[1] ?? '';
  const body = html.match(/<body[^>]*>([\s\S]*?)<\/body>/i)?.[1] ?? '';

  const styles = head.match(/<link[^>]+rel="stylesheet"[^>]*>/gi) ?? [];
  const preloads = head.match(/<link[^>]+rel="modulepreload"[^>]*>/gi) ?? [];
  const headScripts = head.match(/<script[^>]*type="module"[^>]*><\/script>/gi) ?? [];
  const bodyScripts = body.match(/<script[^>]*type="module"[^>]*><\/script>/gi) ?? [];

  return {
    assetsHead: [...preloads, ...styles].join('\n    '),
    assetsScripts: [...headScripts, ...bodyScripts].join('\n    '),
  };
}

async function collectHtmlFiles(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...(await collectHtmlFiles(path)));
    else if (entry.name.endsWith('.html')) found.push(path);
  }
  return found;
}

async function main() {
  const shellPath = join(DIST, 'blog/post.html');
  const built = await readFile(shellPath, 'utf8').catch(() => {
    throw new Error(
      'dist/blog/post.html is missing. The blog shell entry must build before this step runs.'
    );
  });

  const assets = extractAssetTags(built);
  const nav = extractBlock(built, 'nav');
  const footer = extractBlock(built, 'footer');
  const dialog = extractBlock(built, 'dialog');

  if (!assets.assetsScripts) throw new Error('No module script found in dist/blog/post.html');
  if (!nav || !footer || !dialog) {
    throw new Error('Could not extract nav/footer/dialog from dist/blog/post.html');
  }

  const { posts } = JSON.parse(await readFile(resolve('content/blog-posts.json'), 'utf8'));

  const module = `// Generated by scripts/build-blog-shell.mjs during \`npm run build\`.
// Do not edit. Edit blog/post.html or content/blog-posts.json instead.

export const shell = ${JSON.stringify({ ...assets, nav, footer, dialog }, null, 2)};

export const fallbackPosts = ${JSON.stringify(posts, null, 2)};
`;

  await writeFile(resolve('netlify/functions/blog-shell.mjs'), module, 'utf8');

  // These are build artifacts, not pages. Functions own /blog/ and /blog/posts/*.
  await rm(shellPath, { force: true });
  await rm(join(DIST, 'blog'), { recursive: true, force: true });

  await writeFile(
    join(DIST, 'robots.txt'),
    `User-agent: *\nAllow: /\n\nSitemap: ${SITE_URL}/sitemap.xml\n`,
    'utf8'
  );

  for (const file of await collectHtmlFiles(DIST)) {
    const html = await readFile(file, 'utf8');
    if (html.includes('__SITE_URL__')) {
      await writeFile(file, html.replaceAll('__SITE_URL__', SITE_URL), 'utf8');
    }
  }

  console.log(
    `Built blog shell (${posts.length} fallback post${posts.length === 1 ? '' : 's'}) ` +
      `and robots.txt for ${SITE_URL}.`
  );
}

await main();
